import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';

// Development-only generation from an installed official Wrangler package.
// This is an inheritance contract, never a supported-field allowlist.
const packageRoot = process.argv[2];
if (!packageRoot) throw new Error('Usage: node scripts/update-wrangler-environment-contract.mjs <wrangler-package-directory>');
const packageJson = JSON.parse(readFileSync(resolve(packageRoot, 'package.json'), 'utf8'));
if (packageJson.name !== 'wrangler') throw new Error('Expected the official wrangler package');
const bytes = readFileSync(resolve(packageRoot, 'config-schema.json'));
const schema = JSON.parse(bytes.toString('utf8'));
const properties = schema.definitions?.RawEnvironment?.properties;
if (!properties || typeof properties !== 'object') throw new Error('Wrangler RawEnvironment schema was not found');
const fields = Object.entries(properties)
  .filter(([, value]) => /not automatically inherited from the top level environment/i.test(value.description || ''))
  .map(([key]) => key).sort();
if (!fields.includes('vars') || !fields.includes('kv_namespaces') || !fields.includes('queues'))
  throw new Error('The schema no longer describes the expected inheritance contract; review upstream changes');
const output = resolve(import.meta.dirname, '../src/workers-wrangler-environment.generated.ts');
const source = '// Generated by scripts/update-wrangler-environment-contract.mjs. Do not hand-edit.\n' +
  '// Official Wrangler ' + packageJson.version + ', config-schema.json SHA256 ' +
  createHash('sha256').update(bytes).digest('hex') + '.\n' +
  '// Environment inheritance only: unknown deployment fields are not rejected here.\n' +
  'export const WRANGLER_NON_INHERITED_FIELDS = ' + JSON.stringify(fields, null, 2) + ' as const;\n';
writeFileSync(output, source);
console.log(JSON.stringify({wranglerVersion:packageJson.version, fieldCount:fields.length, output}));
